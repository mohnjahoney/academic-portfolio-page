import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';

import { ARTIFACT_TITLE_MORPH_TEXT } from '../artifactTitleMorph.js';
import { GENERATED_GEORGIA_GLYPHS } from '../generated/georgiaTitleGlyphs.js';

const projectRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..'
);
const outputPath = path.join(
  projectRoot,
  'generated',
  'georgiaTitleGlyphs.js'
);
const fromCharacters = Array.from(ARTIFACT_TITLE_MORPH_TEXT.from);
const toCharacters = Array.from(ARTIFACT_TITLE_MORPH_TEXT.to);

if (fromCharacters.length !== toCharacters.length) {
  throw new Error(
    `Title morph strings must have equal lengths: ` +
      `${fromCharacters.length} !== ${toCharacters.length}.`
  );
}

const requiredCharacters = [];

fromCharacters.forEach((character, index) => {
  const alternate = toCharacters[index];

  if (/\s/u.test(character) !== /\s/u.test(alternate)) {
    throw new Error(
      `Title morph cannot add, remove, or alter whitespace at index ${index}.`
    );
  }

  if (/\s/u.test(character)) {
    return;
  }

  [character, alternate].forEach((requiredCharacter) => {
    if (!requiredCharacters.includes(requiredCharacter)) {
      requiredCharacters.push(requiredCharacter);
    }
  });
});

if (process.argv.includes('--check')) {
  const missingCharacters = requiredCharacters.filter(
    (character) => !GENERATED_GEORGIA_GLYPHS.glyphs[character]
  );

  if (missingCharacters.length > 0) {
    throw new Error(
      `Missing generated Georgia glyphs: ${missingCharacters.join(', ')}. ` +
        `Run "npm run glyphs" and commit the updated cache.`
    );
  }

  console.log(
    `Georgia glyph cache covers: ${requiredCharacters.join(', ')}`
  );
  process.exit(0);
}

const fontCandidates = [
  process.env.GEORGIA_FONT_PATH,
  '/System/Library/Fonts/Supplemental/Georgia.ttf',
  '/Library/Fonts/Georgia.ttf',
  '/usr/share/fonts/truetype/msttcorefonts/Georgia.ttf',
  'C:\\Windows\\Fonts\\georgia.ttf'
].filter(Boolean);
const fontPath = fontCandidates.find((candidate) => fs.existsSync(candidate));

if (!fontPath) {
  throw new Error(
    `Georgia.ttf was not found. Set GEORGIA_FONT_PATH to its local path.`
  );
}

const fontBuffer = fs.readFileSync(fontPath);
const font = opentype.parse(
  fontBuffer.buffer.slice(
    fontBuffer.byteOffset,
    fontBuffer.byteOffset + fontBuffer.byteLength
  )
);
const glyphs = Object.fromEntries(
  requiredCharacters.map((character) => {
    const glyph = font.charToGlyph(character);

    if (!glyph || glyph.unicode === undefined) {
      throw new Error(`Georgia does not contain a glyph for "${character}".`);
    }

    return [
      character,
      {
        advanceWidth: glyph.advanceWidth,
        path: glyph
          .getPath(0, 0, font.unitsPerEm)
          .toPathData(2)
      }
    ];
  })
);
const generatedSource =
  `// Generated by \`npm run glyphs\`. Do not edit by hand.\n` +
  `export const GENERATED_GEORGIA_GLYPHS = ${JSON.stringify(
    {
      unitsPerEm: font.unitsPerEm,
      ascender: font.ascender,
      descender: font.descender,
      glyphs
    },
    null,
    2
  )};\n`;

fs.writeFileSync(outputPath, generatedSource);
console.log(
  `Generated ${requiredCharacters.length} Georgia glyphs from ${fontPath}.`
);
